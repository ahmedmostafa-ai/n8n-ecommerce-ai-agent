-- E-Commerce AI Agent — PostgreSQL schema
-- Portfolio reconstruction based on information_schema.columns output.
-- IMPORTANT: Primary/foreign keys, identity generation, unique constraints, and
-- some CHECK constraints cannot be verified from that output alone.
-- Review against the live database before treating this as an exact schema dump.
-- Run only against an EMPTY development database; never against production.

BEGIN;

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL UNIQUE,
    name VARCHAR,
    phone VARCHAR,
    address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    description TEXT,
    price NUMERIC NOT NULL CHECK (price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    status VARCHAR NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
    total_amount NUMERIC NOT NULL CHECK (total_amount >= 0),
    delivery_address TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    request_id UUID UNIQUE
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE checkout_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    delivery_address TEXT NOT NULL CHECK (LENGTH(TRIM(delivery_address)) >= 10),
    status VARCHAR NOT NULL DEFAULT 'awaiting_confirmation'
        CHECK (status IN ('awaiting_confirmation', 'confirmed', 'cancelled', 'expired')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '15 minutes'),
    order_id BIGINT REFERENCES orders(id)
);

-- Allow at most one pending checkout per customer. Expired pending rows
-- must be marked 'expired' before a new checkout can be inserted.
CREATE UNIQUE INDEX idx_one_pending_checkout_per_customer
    ON checkout_sessions(customer_id)
    WHERE status = 'awaiting_confirmation';

COMMIT;
